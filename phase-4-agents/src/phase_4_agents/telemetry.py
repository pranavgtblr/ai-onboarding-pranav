"""Task 5.1: Production Telemetry and Tracing for AI Agents.

Provides:
1. `StepTelemetry`: Pydantic schema recording per-step tokens, cost, and latency.
2. `StepTelemetryTracer`: LangChain `BaseCallbackHandler` capturing real-time metrics
   for LLM invocations and tool executions.
3. Pricing engine computing exact USD cost across model providers.
4. LangSmith configuration helper for cloud tracing integration.
5. Structured JSON logging and formatted ASCII trace summary tables.
"""

from __future__ import annotations

import json
import logging
import os
import time
from datetime import datetime, timezone
from typing import Any
from uuid import UUID

from langchain_core.callbacks import BaseCallbackHandler
from langchain_core.messages import BaseMessage
from langchain_core.outputs import LLMResult
from pydantic import BaseModel, ConfigDict, Field

logger = logging.getLogger("phase_4_agents.telemetry")
if not logger.handlers:
    handler = logging.StreamHandler()
    handler.setFormatter(
        logging.Formatter("[%(asctime)s] [%(levelname)s] [TELEMETRY] %(message)s")
    )
    logger.addHandler(handler)
    logger.setLevel(logging.INFO)

# -----------------------------------------------------------------------------
# 1. Model Pricing Catalog ($ / 1 Million Tokens)
# -----------------------------------------------------------------------------

MODEL_RATES: dict[str, tuple[float, float]] = {
    # model_substring: (input_price_per_1M, output_price_per_1M)
    "gemini-2.5-flash": (0.15, 0.60),
    "gemini-2.0-flash": (0.15, 0.60),
    "gemini-1.5-flash": (0.15, 0.60),
    "gemini-1.5-pro": (1.25, 5.00),
    "gpt-4o-mini": (0.15, 0.60),
    "gpt-4o": (2.50, 10.00),
    "claude-3-5-haiku": (0.80, 4.00),
    "claude-3-5-sonnet": (3.00, 15.00),
    "mock": (0.15, 0.60),
    "default": (0.15, 0.60),
}


def calculate_token_cost(
    model_name: str,
    input_tokens: int,
    output_tokens: int,
) -> float:
    """Calculate the estimated USD cost for a given token usage and model.

    Args:
        model_name: Model identifier string.
        input_tokens: Number of prompt/input tokens.
        output_tokens: Number of completion/output tokens.

    Returns:
        Total estimated cost in USD rounded to 8 decimal places.
    """
    m_lower = (model_name or "default").lower()
    in_rate, out_rate = MODEL_RATES["default"]

    for pattern, rates in MODEL_RATES.items():
        if pattern in m_lower:
            in_rate, out_rate = rates
            break

    input_cost = (input_tokens / 1_000_000.0) * in_rate
    output_cost = (output_tokens / 1_000_000.0) * out_rate
    return round(input_cost + output_cost, 8)


