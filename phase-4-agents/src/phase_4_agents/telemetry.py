def configure_langsmith_tracing(
    project_name: str | None = None,
    api_key: str | None = None,
    endpoint: str | None = None,
) -> bool:
    """Configure environment variables for native LangSmith cloud tracing.

    Args:
        project_name: LangSmith project name (defaults to 'phase-5-production').
        api_key: Optional LangSmith API key override.
        endpoint: Optional LangSmith endpoint override.

    Returns:
        True if LangSmith credentials are present and tracing is activated.
    """
    key = (
        api_key
        or os.environ.get("LANGSMITH_API_KEY")
        or os.environ.get("LANGCHAIN_API_KEY")
    )
    if not key:
        logger.info(
            "LangSmith API key not detected in environment. "
            "Using local StepTelemetryTracer for offline per-step metrics."
        )
        return False

    os.environ["LANGCHAIN_TRACING_V2"] = "true"
    os.environ["LANGSMITH_TRACING"] = "true"
    os.environ["LANGCHAIN_API_KEY"] = key
    os.environ["LANGCHAIN_PROJECT"] = project_name or os.environ.get(
        "LANGCHAIN_PROJECT", "phase-5-production"
    )

    if endpoint:
        os.environ["LANGCHAIN_ENDPOINT"] = endpoint

    proj = os.environ["LANGCHAIN_PROJECT"]
    logger.info(f"LangSmith cloud tracing enabled for project '{proj}'.")
    return True
