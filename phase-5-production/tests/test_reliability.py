def test_degradation_handler_detects_empty_outputs() -> None:
    """Handler correctly identifies zero-record database and empty document outputs."""
    empty_db = (
        "Database Query Results:\n"
        "• Executed SQL: `SELECT ...`\n"
        "• Rows Returned: 0\n"
        "• No matching records found."
    )
    empty_pdf = "No relevant chunks found matching 'nonexistent-topic'."
    non_empty = "Database Query Results:\n• Rows Returned: 1\n• Records: {'id': 1}"

    assert GracefulDegradationHandler.is_empty_retrieval(empty_db) is True
    assert GracefulDegradationHandler.is_empty_retrieval(empty_pdf) is True
    assert GracefulDegradationHandler.is_empty_retrieval("") is True
    assert GracefulDegradationHandler.is_empty_retrieval(non_empty) is False


def test_degradation_handler_formats_grounded_answer() -> None:
    """Degradation notice provides truthful notice without hallucinating."""
    notice = GracefulDegradationHandler.create_degradation_response(
        query="find customers in Atlantis",
        tool_name="db_query",
        tool_output="• Rows Returned: 0\n• No matching records found.",
    )

    assert notice.searched_entity_or_topic == "find customers in Atlantis"
    assert "0 results" in notice.message
    assert len(notice.suggested_alternatives) >= 2

    formatted = GracefulDegradationHandler.format_grounded_answer(notice)
    assert "Notice: Information Not Found" in formatted
    assert "does not generate speculative or unverified answers" in formatted


