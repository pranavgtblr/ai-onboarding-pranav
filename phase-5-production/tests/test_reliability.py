def make_mock_llm(
    return_value: Any = None,
    side_effect: Any = None,
) -> MagicMock:
    """Helper to construct MagicMock working for both direct call and .invoke()."""
    mock = MagicMock()
    if side_effect is not None:
        mock.side_effect = side_effect
        mock.invoke.side_effect = side_effect
    if return_value is not None:
        mock.return_value = return_value
        mock.invoke.return_value = return_value
    return mock


# =====================================================================
# PART 1: Provider Fallback on 429 Rate Limit & 503 Outages
# =====================================================================


def test_fallback_triggers_on_429_rate_limit() -> None:
    """Primary model throwing 429 must trigger automatic secondary failover."""
    primary_mock = make_mock_llm(
        side_effect=Exception("429 Too Many Requests: ResourceExhausted quota exceeded")
    )
    fallback_mock = make_mock_llm(
        return_value=AIMessage(content="Response generated by secondary provider.")
    )

    captured_events: list[ProviderFailoverEvent] = []
    model = ReliableFallbackModel(
        primary_model=primary_mock,
        fallback_model=fallback_mock,
        primary_name="gemini-1.5-flash",
        fallback_name="gpt-4o-mini",
        failover_callback=captured_events.append,
    )

    result = model.invoke([AIMessage(content="Hello")])

    assert result.content == "Response generated by secondary provider."
    assert model.failover_count == 1
    assert model.primary_successes == 0
    assert model.fallback_successes == 1
    assert len(captured_events) == 1
    assert captured_events[0].reason == "rate_limit"
    assert captured_events[0].primary_provider == "gemini-1.5-flash"
    assert captured_events[0].fallback_provider == "gpt-4o-mini"


def test_fallback_triggers_on_503_service_outage() -> None:
    """Primary model throwing 503 Service Unavailable must trigger failover."""
    primary_mock = make_mock_llm(
        side_effect=Exception("503 Service Unavailable: High server load / outage")
    )
    fallback_mock = make_mock_llm(
        return_value=AIMessage(content="Fallback response during outage.")
    )

    captured_events: list[ProviderFailoverEvent] = []
    model = ReliableFallbackModel(
        primary_model=primary_mock,
        fallback_model=fallback_mock,
        primary_name="gemini-primary",
        fallback_name="backup-provider",
        failover_callback=captured_events.append,
    )

    result = model.invoke([AIMessage(content="Status report")])

    assert result.content == "Fallback response during outage."
    assert model.failover_count == 1
    assert captured_events[0].reason == "outage"


def test_fallback_triggers_on_connection_timeout() -> None:
    """Connection timeouts to primary must failover gracefully."""
    primary_mock = make_mock_llm(
        side_effect=TimeoutError("Connection timed out to primary API gateway")
    )
    fallback_mock = make_mock_llm(
        return_value=AIMessage(content="Response served by backup provider.")
    )

    model = ReliableFallbackModel(
        primary_model=primary_mock,
        fallback_model=fallback_mock,
    )

    result = model.invoke([AIMessage(content="Ping")])
    assert result.content == "Response served by backup provider."
    assert model.failover_count == 1


def test_non_transient_error_is_not_swallowed() -> None:
    """Non-transient programming errors (e.g. ValueError) must not trigger failover."""
    primary_mock = make_mock_llm(side_effect=ValueError("Invalid argument value"))
    fallback_mock = make_mock_llm()

    model = ReliableFallbackModel(
        primary_model=primary_mock,
        fallback_model=fallback_mock,
    )

    with pytest.raises(ValueError, match="Invalid argument value"):
        model.invoke([AIMessage(content="Bad call")])

    assert fallback_mock.call_count == 0
    assert model.failover_count == 0


def test_both_providers_failing_raises_exception() -> None:
    """When both primary and secondary fail, the exception is propagated cleanly."""
    primary_mock = make_mock_llm(side_effect=Exception("500 Internal Server Error"))
    fallback_mock = make_mock_llm(side_effect=Exception("503 Backup unavailable"))

    model = ReliableFallbackModel(
        primary_model=primary_mock,
        fallback_model=fallback_mock,
    )

    with pytest.raises(Exception, match="503 Backup unavailable"):
        model.invoke([AIMessage(content="Query")])


