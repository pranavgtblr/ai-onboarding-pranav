def test_reliable_agent_failover_integration() -> None:
    """Agent seamlessly falls back to backup LLM and reports failover telemetry."""
    primary_mock = make_mock_llm(
        side_effect=Exception("429 Too Many Requests: Quota exceeded")
    )
    fallback_mock = make_mock_llm(
        return_value=AIMessage(content="Answer produced by fallback provider.")
    )

    fallback_model = ReliableFallbackModel(
        primary_model=primary_mock,
        fallback_model=fallback_mock,
        primary_name="gemini-primary",
        fallback_name="openai-backup",
    )

    agent = ReliableAgent(fallback_model=fallback_model)
    res = agent.run_query("Explain planetary orbits.")

    assert res.response == "Answer produced by fallback provider."
    assert res.failover_occurred is True
    assert res.active_provider == "openai-backup"
    assert res.failover_reason == "rate_limit"
    assert res.is_degraded is False


def test_reliable_agent_empty_retrieval_degradation() -> None:
    """Agent gracefully degrades when tool finds no records without calling LLM."""
    primary_mock = make_mock_llm()
    fallback_mock = make_mock_llm()

    fallback_model = ReliableFallbackModel(
        primary_model=primary_mock,
        fallback_model=fallback_mock,
    )

    # Wire real db_query tool
    agent = ReliableAgent(
        fallback_model=fallback_model,
        tools_map={"db_query": lambda q: db_query.invoke({"query": q})},
    )

    # Query for city that does not exist in db
    res = agent.run_query(
        query="find customers in Atlantis",
        tool_name="db_query",
    )

    assert res.is_degraded is True
    assert "Notice: Information Not Found" in res.response
    assert "Atlantis" in res.response
    # Primary LLM was spared from hallucinating or generating fake customers
    assert primary_mock.call_count == 0
    assert fallback_mock.call_count == 0
